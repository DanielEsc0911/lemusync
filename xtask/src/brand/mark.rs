//! Compose a lemur mark: SVG parts + colors + params + the built-in tail → one SVG.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use serde::Deserialize;

use super::tokens::{Rgb, Tokens};

const GENERATED: &str = "<!-- GENERATED by cargo xtask brand from brand/. Do not edit. -->";

#[derive(Debug, Deserialize)]
struct Tail {
    cx: f64,
    cy: f64,
    r: f64,
    start_deg: f64,
    sweep_deg: f64,
    width: f64,
    rings: f64,
}

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct MarkDef {
    extends: Option<String>,
    parts: Option<Vec<String>>,
    #[serde(default)]
    colors: BTreeMap<String, String>,
    #[serde(default)]
    params: BTreeMap<String, f64>,
}

#[derive(Debug, Deserialize)]
struct File {
    schema: u32,
    tail: Tail,
    mark: BTreeMap<String, MarkDef>,
}

/// The parsed `marks.toml`.
#[derive(Debug)]
pub struct Marks(File);

impl Marks {
    /// Every mark name, sorted.
    #[cfg(test)]
    pub fn names(&self) -> Vec<&str> {
        self.0.mark.keys().map(String::as_str).collect()
    }
}

pub fn load_marks(path: &Path) -> Result<Marks, Vec<String>> {
    let text = fs::read_to_string(path).map_err(|e| vec![format!("{}: {e}", path.display())])?;
    load_marks_str(&text)
}

pub fn load_marks_str(text: &str) -> Result<Marks, Vec<String>> {
    let file: File = toml::from_str(text).map_err(|e| vec![format!("marks.toml: {e}")])?;
    if file.schema != 1 {
        return Err(vec![format!(
            "marks.toml: unsupported schema {}",
            file.schema
        )]);
    }
    Ok(Marks(file))
}

/// Part names come from data: restrict them before they touch the file system.
pub fn safe_name(name: &str) -> bool {
    !name.is_empty()
        && !name.contains("..")
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'@' | b'.' | b'_' | b'-'))
}

struct Resolved {
    parts: Vec<String>,
    colors: BTreeMap<String, String>,
    params: BTreeMap<String, f64>,
}

fn resolve(name: &str, marks: &Marks, seen: &mut Vec<String>) -> Result<Resolved, String> {
    if seen.iter().any(|s| s == name) {
        return Err(format!(
            "mark `{name}`: `extends` cycle ({})",
            seen.join(" -> ")
        ));
    }
    let def = marks.0.mark.get(name).ok_or_else(|| {
        format!(
            "mark `{name}`: unknown mark (parent `{}`)",
            seen.last().map_or("-", String::as_str)
        )
    })?;
    seen.push(name.to_string());
    let mut out = match &def.extends {
        Some(parent) => resolve(parent, marks, seen)?,
        None => Resolved {
            parts: Vec::new(),
            colors: BTreeMap::new(),
            params: BTreeMap::new(),
        },
    };
    seen.pop();
    if let Some(parts) = &def.parts {
        out.parts.clone_from(parts);
    }
    out.colors.extend(def.colors.clone());
    out.params.extend(def.params.clone());
    Ok(out)
}

fn num(v: f64) -> String {
    format!("{v}")
}

fn hex(c: Rgb) -> String {
    format!("#{:02X}{:02X}{:02X}", c.0, c.1, c.2)
}

/// The text values a part may use as `{{param.x}}`: numbers plus the derived ones.
fn derive_params(
    r: &Resolved,
    tokens: &Tokens,
    mark: &str,
) -> Result<BTreeMap<String, String>, String> {
    let mut p: BTreeMap<String, String> =
        r.params.iter().map(|(k, v)| (k.clone(), num(*v))).collect();
    if let Some(symbol) = r.params.get("symbol") {
        for i in 1..=6u32 {
            let on = (symbol - f64::from(i)).abs() < 1e-9;
            p.insert(
                format!("show{i}"),
                if on { "inline" } else { "none" }.to_string(),
            );
        }
    }
    let hollow = r
        .params
        .get("hollow")
        .is_some_and(|h| (h - 1.0).abs() < 1e-9);
    if hollow {
        p.insert("dotFill".into(), "none".into());
    } else if let Some(status) = r.colors.get("status") {
        let c = tokens.primitive(status).ok_or_else(|| {
            format!("mark `{mark}`: color `status`: unknown primitive `{status}`")
        })?;
        p.insert("dotFill".into(), hex(c));
    }
    Ok(p)
}

fn substitute(
    text: &str,
    r: &Resolved,
    derived: &BTreeMap<String, String>,
    tokens: &Tokens,
    mark: &str,
    part: &str,
) -> Result<String, String> {
    let mut out = String::new();
    let mut rest = text;
    while let Some(start) = rest.find("{{") {
        out.push_str(&rest[..start]);
        let after = &rest[start + 2..];
        let end = after
            .find("}}")
            .ok_or_else(|| format!("mark `{mark}`, part `{part}`: unterminated placeholder"))?;
        let key = after[..end].trim();
        if let Some(c) = key.strip_prefix("color.") {
            let prim = r
                .colors
                .get(c)
                .ok_or_else(|| format!("mark `{mark}`, part `{part}`: unknown color key `{c}`"))?;
            let rgb = tokens.primitive(prim).ok_or_else(|| {
                format!("mark `{mark}`, part `{part}`: color `{c}`: unknown primitive `{prim}`")
            })?;
            out.push_str(&hex(rgb));
        } else if let Some(k) = key.strip_prefix("param.") {
            let v = derived.get(k).ok_or_else(|| {
                format!("mark `{mark}`, part `{part}`: unknown placeholder `{key}`")
            })?;
            out.push_str(v);
        } else {
            return Err(format!(
                "mark `{mark}`, part `{part}`: unknown placeholder `{key}`"
            ));
        }
        rest = &after[end + 2..];
    }
    out.push_str(rest);
    Ok(out)
}

/// The built-in tail: ring-colored arc, stripe-colored dashes over it, an arrowhead at the end.
fn tail_svg(t: &Tail, r: &Resolved, tokens: &Tokens, mark: &str) -> Result<String, String> {
    let color = |key: &str| -> Result<String, String> {
        let prim = r
            .colors
            .get(key)
            .ok_or_else(|| format!("mark `{mark}`, part `tail`: unknown color key `{key}`"))?;
        tokens.primitive(prim).map(hex).ok_or_else(|| {
            format!("mark `{mark}`, part `tail`: color `{key}`: unknown primitive `{prim}`")
        })
    };
    let (ring, stripe) = (color("ring")?, color("stripe")?);
    let a0 = t.start_deg.to_radians();
    let a1 = (t.start_deg + t.sweep_deg).to_radians();
    let (x0, y0) = (t.cx + t.r * a0.cos(), t.cy + t.r * a0.sin());
    let (x1, y1) = (t.cx + t.r * a1.cos(), t.cy + t.r * a1.sin());
    let large = i32::from(t.sweep_deg > 180.0);
    let len = t.r * t.sweep_deg.to_radians();
    let dash = len / (2.0 * t.rings);
    let arc = format!(
        "M{x0:.2} {y0:.2}A{r:.2} {r:.2} 0 {large} 1 {x1:.2} {y1:.2}",
        r = t.r
    );
    // Clockwise tangent at the end; the arrowhead base spans the radial direction.
    let (tx, ty) = (-a1.sin(), a1.cos());
    let (nx, ny) = (a1.cos(), a1.sin());
    let half = t.width * 0.9;
    let tip = t.width * 1.4;
    let tri = format!(
        "{:.2} {:.2} {:.2} {:.2} {:.2} {:.2}",
        x1 + nx * half,
        y1 + ny * half,
        x1 - nx * half,
        y1 - ny * half,
        x1 + tx * tip,
        y1 + ty * tip
    );
    let w = t.width;
    Ok(format!(
        "<path d=\"{arc}\" fill=\"none\" stroke=\"{ring}\" stroke-width=\"{w}\" stroke-linecap=\"butt\"/>\n\
         <path d=\"{arc}\" fill=\"none\" stroke=\"{stripe}\" stroke-width=\"{w}\" stroke-linecap=\"butt\" stroke-dasharray=\"{dash:.2} {dash:.2}\"/>\n\
         <polygon points=\"{tri}\" fill=\"{stripe}\"/>\n"
    ))
}

/// Composes `name` into a complete SVG document.
pub fn compose(
    name: &str,
    marks: &Marks,
    tokens: &Tokens,
    parts_dir: &Path,
) -> Result<String, String> {
    let r = resolve(name, marks, &mut Vec::new())?;
    let derived = derive_params(&r, tokens, name)?;
    let mut svg = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 256 256\">\n{GENERATED}\n"
    );
    for part in &r.parts {
        if part == "tail" {
            svg.push_str(&tail_svg(&marks.0.tail, &r, tokens, name)?);
            continue;
        }
        if !safe_name(part) {
            return Err(format!("mark `{name}`: bad part name `{part}`"));
        }
        let file = parts_dir.join(format!("{part}.svg"));
        let text = fs::read_to_string(&file)
            .map_err(|e| format!("mark `{name}`: missing part file {}: {e}", file.display()))?;
        let body = substitute(&text, &r, &derived, tokens, name, part)?;
        svg.push_str(body.trim_end());
        svg.push('\n');
    }
    svg.push_str("</svg>\n");
    Ok(svg)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tokens() -> Tokens {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../brand/tokens.toml");
        Tokens::load(&root).unwrap()
    }

    fn fixture(parts: &[(&str, &str)], marks: &str) -> (tempfile::TempDir, Marks) {
        let dir = tempfile::tempdir().unwrap();
        for (n, t) in parts {
            fs::write(dir.path().join(format!("{n}.svg")), t).unwrap();
        }
        let toml = format!(
            "schema = 1\n[tail]\ncx=128\ncy=136\nr=96\nstart_deg=115\nsweep_deg=290\nwidth=22\nrings=7\n{marks}"
        );
        (dir, load_marks_str(&toml).unwrap())
    }

    #[test]
    fn substitutes_colors_and_params() {
        let (d, m) = fixture(
            &[
                ("a", "<rect fill=\"{{color.c}}\" x=\"{{param.x}}\"/>"),
                ("b", "<g/>"),
            ],
            "[mark.m]\nparts=[\"a\",\"b\"]\ncolors={c=\"bone\"}\nparams={x=16}\n",
        );
        let svg = compose("m", &m, &tokens(), d.path()).unwrap();
        assert!(svg.contains("fill=\"#FBFAF7\" x=\"16\""), "{svg}");
        assert!(svg.contains("GENERATED"));
        assert!(svg.find("<rect").unwrap() < svg.find("<g/>").unwrap());
    }

    #[test]
    fn child_overrides_key_by_key_and_parts_replace() {
        let (d, m) = fixture(
            &[("a", "{{color.c}}{{param.x}}{{param.y}}"), ("b", "B")],
            "[mark.p]\nparts=[\"a\",\"b\"]\ncolors={c=\"bone\"}\nparams={x=1,y=2}\n\
             [mark.k]\nextends=\"p\"\ncolors={c=\"amber-500\"}\nparams={x=9}\n\
             [mark.q]\nextends=\"p\"\nparts=[\"b\"]\n",
        );
        let k = compose("k", &m, &tokens(), d.path()).unwrap();
        assert!(k.contains("#E89B2D92"), "{k}");
        assert!(k.contains('B'));
        let q = compose("q", &m, &tokens(), d.path()).unwrap();
        assert!(!q.contains("#FBFAF7"));
    }

    #[test]
    fn symbol_selects_one_group_and_hollow_clears_fill() {
        let part = "{{param.show1}}{{param.show2}}{{param.show3}}|{{param.dotFill}}";
        let (d, m) = fixture(
            &[("a", part)],
            "[mark.s]\nparts=[\"a\"]\ncolors={status=\"green-500\"}\nparams={symbol=3}\n\
             [mark.h]\nextends=\"s\"\nparams={hollow=1}\n",
        );
        let s = compose("s", &m, &tokens(), d.path()).unwrap();
        assert!(s.contains("nonenoneinline|#2F9E55"), "{s}");
        let h = compose("h", &m, &tokens(), d.path()).unwrap();
        assert!(h.contains("|none"), "{h}");
    }

    #[test]
    fn dasharray_is_a_fourteenth_of_the_arc() {
        let (d, m) = fixture(
            &[],
            "[mark.t]\nparts=[\"tail\"]\ncolors={ring=\"bone\",stripe=\"charcoal-950\"}\n",
        );
        let svg = compose("t", &m, &tokens(), d.path()).unwrap();
        let l = 96.0 * 290.0 * std::f64::consts::PI / 180.0;
        let want = format!("stroke-dasharray=\"{0:.2} {0:.2}\"", l / 14.0);
        assert!(svg.contains(&want), "{svg} / {want}");
        assert!(svg.contains(" 0 1 1 "), "large-arc flag");
    }

    #[test]
    fn errors_name_the_mark() {
        let (d, m) = fixture(
            &[
                ("a", "{{param.nope}}"),
                ("c", "{{color.nope}}"),
                ("e", "{{oops}}"),
            ],
            "[mark.u]\nparts=[\"a\"]\n[mark.col]\nparts=[\"c\"]\n[mark.o]\nparts=[\"e\"]\n\
             [mark.prim]\nparts=[\"c\"]\ncolors={nope=\"mauve\"}\n\
             [mark.miss]\nparts=[\"zzz\"]\n[mark.bad]\nparts=[\"../x\"]\n\
             [mark.c1]\nextends=\"c2\"\n[mark.c2]\nextends=\"c1\"\n[mark.orph]\nextends=\"ghost\"\n",
        );
        for (name, needle) in [
            ("u", "unknown placeholder"),
            ("col", "unknown color key"),
            ("o", "unknown placeholder"),
            ("prim", "unknown primitive"),
            ("miss", "missing part file"),
            ("bad", "bad part name"),
            ("c1", "cycle"),
            ("orph", "unknown mark"),
        ] {
            let e = compose(name, &m, &tokens(), d.path()).unwrap_err();
            assert!(e.contains(needle) && e.contains(name), "{name}: {e}");
        }
    }

    #[test]
    fn real_marks_compose() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../brand");
        let marks = load_marks(&root.join("mark/marks.toml")).unwrap();
        for name in marks.names() {
            if name == "tray" {
                continue; // a base without a status color; never an output
            }
            compose(name, &marks, &tokens(), &root.join("mark/parts"))
                .unwrap_or_else(|e| panic!("{e}"));
        }
    }
}
