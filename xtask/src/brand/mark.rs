//! Compose a lemur mark: SVG parts + colors + params + the built-in tail → one SVG.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use serde::Deserialize;

use super::tokens::{Rgb, Tokens};

const GENERATED: &str = "<!-- GENERATED by cargo xtask brand from brand/. Do not edit. -->";

const fn default_head_half() -> f64 {
    0.9
}

const fn default_head_len() -> f64 {
    1.4
}

/// The base `[tail]`: angles in degrees (0 = 3 o'clock, clockwise), sizes in 256-space units.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct Tail {
    cx: f64,
    cy: f64,
    r: f64,
    start_deg: f64,
    sweep_deg: f64,
    width: f64,
    rings: f64,
    /// Arrowhead half-base, in multiples of `width`.
    #[serde(default = "default_head_half")]
    head_half: f64,
    /// Arrowhead length, in multiples of `width`.
    #[serde(default = "default_head_len")]
    head_len: f64,
}

/// A per-mark `[mark.<name>.tail]`: any `[tail]` key, applied over the inherited tail.
#[derive(Debug, Default, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct TailPatch {
    cx: Option<f64>,
    cy: Option<f64>,
    r: Option<f64>,
    start_deg: Option<f64>,
    sweep_deg: Option<f64>,
    width: Option<f64>,
    rings: Option<f64>,
    head_half: Option<f64>,
    head_len: Option<f64>,
}

impl Tail {
    fn apply(&mut self, p: &TailPatch) {
        macro_rules! set {
            ($($f:ident),*) => { $(if let Some(v) = p.$f { self.$f = v; })* };
        }
        set!(
            cx, cy, r, start_deg, sweep_deg, width, rings, head_half, head_len
        );
    }

    fn validate(&self, mark: &str) -> Result<(), String> {
        let fields = [
            ("cx", self.cx),
            ("cy", self.cy),
            ("r", self.r),
            ("start_deg", self.start_deg),
            ("sweep_deg", self.sweep_deg),
            ("width", self.width),
            ("rings", self.rings),
            ("head_half", self.head_half),
            ("head_len", self.head_len),
        ];
        let bad = |f: &str, why: &str| Err(format!("mark `{mark}`: tail.{f} {why}"));
        for (name, v) in fields {
            if !v.is_finite() {
                return bad(name, "must be a finite number");
            }
        }
        for (name, v) in [
            ("r", self.r),
            ("width", self.width),
            ("head_half", self.head_half),
            ("head_len", self.head_len),
        ] {
            if v <= 0.0 {
                return bad(name, "must be greater than 0");
            }
        }
        if self.rings < 1.0 || self.rings.fract() != 0.0 {
            return bad("rings", "must be a whole number, at least 1");
        }
        if self.sweep_deg <= 0.0 || self.sweep_deg >= 360.0 {
            return bad("sweep_deg", "must be between 0 and 360 (exclusive)");
        }
        Ok(())
    }

    fn start(&self) -> (f64, f64) {
        let a = self.start_deg.to_radians();
        (self.cx + self.r * a.cos(), self.cy + self.r * a.sin())
    }

    fn end(&self) -> (f64, f64) {
        let a = (self.start_deg + self.sweep_deg).to_radians();
        (self.cx + self.r * a.cos(), self.cy + self.r * a.sin())
    }
}

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct MarkDef {
    extends: Option<String>,
    parts: Option<Vec<String>>,
    #[serde(default)]
    colors: BTreeMap<String, String>,
    #[serde(default)]
    params: BTreeMap<String, f64>,
    tail: Option<TailPatch>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct File {
    schema: u32,
    tail: Tail,
    mark: BTreeMap<String, MarkDef>,
}

/// The parsed `marks.toml`.
#[derive(Debug)]
pub struct Marks(File);

impl Marks {
    /// Every mark name, sorted.
    #[cfg(test)]
    pub fn names(&self) -> Vec<&str> {
        self.0.mark.keys().map(String::as_str).collect()
    }
}

pub fn load_marks(path: &Path) -> Result<Marks, Vec<String>> {
    let text = fs::read_to_string(path).map_err(|e| vec![format!("{}: {e}", path.display())])?;
    load_marks_str(&text)
}

pub fn load_marks_str(text: &str) -> Result<Marks, Vec<String>> {
    let file: File = toml::from_str(text).map_err(|e| vec![format!("marks.toml: {e}")])?;
    if file.schema != 1 {
        return Err(vec![format!(
            "marks.toml: unsupported schema {}",
            file.schema
        )]);
    }
    Ok(Marks(file))
}

/// Part names come from data: restrict them before they touch the file system.
pub fn safe_name(name: &str) -> bool {
    !name.is_empty()
        && !name.contains("..")
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'@' | b'.' | b'_' | b'-'))
}

struct Resolved {
    parts: Vec<String>,
    colors: BTreeMap<String, String>,
    params: BTreeMap<String, f64>,
    tail: Tail,
}

fn resolve(name: &str, marks: &Marks, seen: &mut Vec<String>) -> Result<Resolved, String> {
    if seen.iter().any(|s| s == name) {
        return Err(format!(
            "mark `{name}`: `extends` cycle ({})",
            seen.join(" -> ")
        ));
    }
    let def = marks.0.mark.get(name).ok_or_else(|| {
        seen.last().map_or_else(
            || format!("mark `{name}`: unknown mark"),
            |child| format!("mark `{child}`: extends unknown mark `{name}`"),
        )
    })?;
    seen.push(name.to_string());
    let mut out = match &def.extends {
        Some(parent) => resolve(parent, marks, seen)?,
        None => Resolved {
            parts: Vec::new(),
            colors: BTreeMap::new(),
            params: BTreeMap::new(),
            tail: marks.0.tail.clone(),
        },
    };
    seen.pop();
    if let Some(parts) = &def.parts {
        out.parts.clone_from(parts);
    }
    out.colors.extend(def.colors.clone());
    out.params.extend(def.params.clone());
    if let Some(patch) = &def.tail {
        out.tail.apply(patch);
    }
    Ok(out)
}

fn num(v: f64) -> String {
    format!("{v}")
}

fn hex(c: Rgb) -> String {
    format!("#{:02X}{:02X}{:02X}", c.0, c.1, c.2)
}

/// Checks the resolved mark: tail numbers, status-dot params, and every color against the palette.
fn validate(name: &str, r: &Resolved, tokens: &Tokens) -> Result<(), String> {
    r.tail.validate(name)?;
    for (key, prim) in &r.colors {
        if tokens.primitive(prim).is_none() {
            return Err(format!(
                "mark `{name}`: color `{key}`: unknown primitive `{prim}`"
            ));
        }
    }
    if r.parts.iter().any(|p| p == "status-dot") {
        let whole = |v: f64| v.fract() == 0.0;
        if let Some(&s) = r
            .params
            .get("symbol")
            .filter(|s| !(whole(**s) && (1.0..=6.0).contains(*s)))
        {
            return Err(format!(
                "mark `{name}`: param `symbol` must be a whole number from 1 to 6, not {s}"
            ));
        }
        if let Some(&h) = r
            .params
            .get("hollow")
            .filter(|h| !(whole(**h) && (0.0..=1.0).contains(*h)))
        {
            return Err(format!(
                "mark `{name}`: param `hollow` must be 0 or 1, not {h}"
            ));
        }
    }
    Ok(())
}

/// The text values a part may use as `{{param.x}}`: numbers plus the derived ones.
fn derive_params(
    r: &Resolved,
    tokens: &Tokens,
    mark: &str,
) -> Result<BTreeMap<String, String>, String> {
    let mut p: BTreeMap<String, String> =
        r.params.iter().map(|(k, v)| (k.clone(), num(*v))).collect();
    if let Some(symbol) = r.params.get("symbol") {
        for i in 1..=6u32 {
            let on = (symbol - f64::from(i)).abs() < 1e-9;
            p.insert(
                format!("show{i}"),
                if on { "inline" } else { "none" }.to_string(),
            );
        }
    }
    let hollow = r
        .params
        .get("hollow")
        .is_some_and(|h| (h - 1.0).abs() < 1e-9);
    if hollow {
        p.insert("dotFill".into(), "none".into());
    } else if let Some(status) = r.colors.get("status") {
        let c = tokens.primitive(status).ok_or_else(|| {
            format!("mark `{mark}`: color `status`: unknown primitive `{status}`")
        })?;
        p.insert("dotFill".into(), hex(c));
    }
    let t = &r.tail;
    let (sx, sy) = t.start();
    let (ex, ey) = t.end();
    for (k, v) in [
        ("tailCx", t.cx),
        ("tailCy", t.cy),
        ("tailR", t.r),
        ("tailWidth", t.width),
        ("tailStartX", sx),
        ("tailStartY", sy),
        ("tailEndX", ex),
        ("tailEndY", ey),
    ] {
        p.insert(k.into(), format!("{v:.2}"));
    }
    Ok(p)
}

fn substitute(
    text: &str,
    r: &Resolved,
    derived: &BTreeMap<String, String>,
    tokens: &Tokens,
    mark: &str,
    part: &str,
) -> Result<String, String> {
    let mut out = String::new();
    let mut rest = text;
    while let Some(start) = rest.find("{{") {
        out.push_str(&rest[..start]);
        let after = &rest[start + 2..];
        let end = after
            .find("}}")
            .ok_or_else(|| format!("mark `{mark}`, part `{part}`: unterminated placeholder"))?;
        let key = after[..end].trim();
        if let Some(c) = key.strip_prefix("color.") {
            let prim = r
                .colors
                .get(c)
                .ok_or_else(|| format!("mark `{mark}`, part `{part}`: unknown color key `{c}`"))?;
            let rgb = tokens.primitive(prim).ok_or_else(|| {
                format!("mark `{mark}`, part `{part}`: color `{c}`: unknown primitive `{prim}`")
            })?;
            out.push_str(&hex(rgb));
        } else if let Some(k) = key.strip_prefix("param.") {
            let v = derived.get(k).ok_or_else(|| {
                format!("mark `{mark}`, part `{part}`: unknown placeholder `{key}`")
            })?;
            out.push_str(v);
        } else {
            return Err(format!(
                "mark `{mark}`, part `{part}`: unknown placeholder `{key}`"
            ));
        }
        rest = &after[end + 2..];
    }
    out.push_str(rest);
    Ok(out)
}

/// The built-in tail: an optional halo, a ring-colored arc, stripe-colored dashes over it, and an
/// arrowhead (`arrow` color, else `stripe`) at the end.
fn tail_svg(r: &Resolved, tokens: &Tokens, mark: &str) -> Result<String, String> {
    let t = &r.tail;
    let lookup = |key: &str| -> Result<Option<String>, String> {
        r.colors
            .get(key)
            .map(|prim| {
                tokens.primitive(prim).map(hex).ok_or_else(|| {
                    format!("mark `{mark}`: color `{key}`: unknown primitive `{prim}`")
                })
            })
            .transpose()
    };
    let need = |key: &str| -> Result<String, String> {
        lookup(key)?.ok_or_else(|| format!("mark `{mark}`, part `tail`: unknown color key `{key}`"))
    };
    let (ring, stripe) = (need("ring")?, need("stripe")?);
    let arrow = lookup("arrow")?.unwrap_or_else(|| stripe.clone());
    let halo = lookup("tailHalo")?;
    let halo_width = r.params.get("haloWidth").copied().unwrap_or(0.0);
    let a1 = (t.start_deg + t.sweep_deg).to_radians();
    let ((x0, y0), (x1, y1)) = (t.start(), t.end());
    let large = i32::from(t.sweep_deg > 180.0);
    let len = t.r * t.sweep_deg.to_radians();
    let dash = len / (2.0 * t.rings);
    let arc = format!(
        "M{x0:.2} {y0:.2}A{r:.2} {r:.2} 0 {large} 1 {x1:.2} {y1:.2}",
        r = t.r
    );
    // Clockwise tangent at the end; the arrowhead base spans the radial direction.
    let (tx, ty) = (-a1.sin(), a1.cos());
    let (nx, ny) = (a1.cos(), a1.sin());
    let base = t.width * t.head_half;
    let tip = t.width * t.head_len;
    let tri = format!(
        "{:.2} {:.2} {:.2} {:.2} {:.2} {:.2}",
        x1 + nx * base,
        y1 + ny * base,
        x1 - nx * base,
        y1 - ny * base,
        x1 + tx * tip,
        y1 + ty * tip
    );
    let w = t.width;
    let mut out = String::new();
    if let (Some(color), true) = (&halo, halo_width > 0.0) {
        let hw = w + 2.0 * halo_width;
        let _ = writeln!(
            out,
            "<path d=\"{arc}\" fill=\"none\" stroke=\"{color}\" stroke-width=\"{hw}\" stroke-linecap=\"butt\"/>"
        );
    }
    let _ = write!(
        out,
        "<path d=\"{arc}\" fill=\"none\" stroke=\"{ring}\" stroke-width=\"{w}\" stroke-linecap=\"butt\"/>\n\
         <path d=\"{arc}\" fill=\"none\" stroke=\"{stripe}\" stroke-width=\"{w}\" stroke-linecap=\"butt\" stroke-dasharray=\"{dash:.2} {dash:.2}\"/>\n\
         <polygon points=\"{tri}\" fill=\"{arrow}\"/>\n"
    );
    Ok(out)
}

/// Parts are fragments of the mark, never a way to reach other files: only `#id` references.
fn check_hrefs(text: &str, mark: &str, part: &str) -> Result<(), String> {
    let mut rest = text;
    while let Some(i) = rest.find("href") {
        let after = rest[i + 4..].trim_start();
        rest = &rest[i + 4..];
        let Some(value) = after.strip_prefix('=') else {
            continue;
        };
        let value = value.trim_start().trim_start_matches(['"', '\'']);
        if !value.starts_with('#') {
            return Err(format!(
                "mark `{mark}`, part `{part}`: `href` must point to an `#id`, never a file or URL"
            ));
        }
    }
    Ok(())
}

/// Composes `name` into a complete SVG document.
pub fn compose(
    name: &str,
    marks: &Marks,
    tokens: &Tokens,
    parts_dir: &Path,
) -> Result<String, String> {
    let r = resolve(name, marks, &mut Vec::new())?;
    validate(name, &r, tokens)?;
    let derived = derive_params(&r, tokens, name)?;
    let mut svg = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 256 256\">\n{GENERATED}\n"
    );
    for part in &r.parts {
        if part == "tail" {
            svg.push_str(&tail_svg(&r, tokens, name)?);
            continue;
        }
        if !safe_name(part) {
            return Err(format!("mark `{name}`: bad part name `{part}`"));
        }
        let file = parts_dir.join(format!("{part}.svg"));
        let text = fs::read_to_string(&file)
            .map_err(|e| format!("mark `{name}`: missing part file {}: {e}", file.display()))?;
        check_hrefs(&text, name, part)?;
        let body = substitute(&text, &r, &derived, tokens, name, part)?;
        svg.push_str(body.trim_end());
        svg.push('\n');
    }
    svg.push_str("</svg>\n");
    Ok(svg)
}

